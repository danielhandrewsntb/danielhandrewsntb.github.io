function highlightPeriod(periodKey) {
  if (!earningsChart) return;
  const idx = PERIODS.findIndex(p => p.key === periodKey);
  const baseColors = [
    [77, 208, 225],
    [255, 178, 76]
  ];

  if (currentChartType === 'bar') {
    earningsChart.data.datasets.forEach((ds, dsIndex) => {
      const [r, g, b] = baseColors[dsIndex];
      ds.backgroundColor = PERIODS.map((_, i) => `rgba(${r}, ${g}, ${b}, ${i === idx ? 0.95 : 0.25})`);
    });
  } else {
    // line / scatter: emphasize the selected point instead of bar opacity
    earningsChart.data.datasets.forEach((ds, dsIndex) => {
      const [r, g, b] = baseColors[dsIndex];
      const pointColors = PERIODS.map((_, i) => `rgba(${r}, ${g}, ${b}, ${i === idx ? 1 : 0.35})`);
      ds.pointBackgroundColor = pointColors;
      ds.pointRadius = PERIODS.map((_, i) => (i === idx ? 7 : 4));
    });
  }

  earningsChart.update();
}

