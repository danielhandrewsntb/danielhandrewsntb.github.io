function averageByPeriod(entries) {
  return PERIODS.map((_, i) => {
    const vals = entries.map(e => e.returns[i]).filter(v => v !== null && v !== undefined && !Number.isNaN(v));
    if (!vals.length) return null;
    return vals.reduce((a, b) => a + b, 0) / vals.length;
  });
}
function medianByPeriod(entries) {
  return PERIODS.map((_, i) => {
    const vals = entries
      .map(e => e.returns[i])
      .filter(v => v !== null && v !== undefined && !Number.isNaN(v))
      .sort((a, b) => a - b);
    if (!vals.length) return null;
    const mid = Math.floor(vals.length / 2);
    return vals.length % 2 !== 0 ? vals[mid] : (vals[mid - 1] + vals[mid]) / 2;
  });
}
function formatCurrency(v, isLoss = false) {
  const sign = isLoss ? '-' : '';
  return sign + '$' + Math.abs(v).toLocaleString(undefined, {
    minimumFractionDigits: 2,
    maximumFractionDigits: 2
  });
}

function updateHeroCalculation() {
  const amountInput = document.getElementById('invest-amount');
  const periodLabelEl = document.getElementById('hero-period-label');
  const wsbEl = document.getElementById('wsb-result-value');
  const etfEl = document.getElementById('etf-result-value');
  if (!amountInput || !wsbEl || !etfEl) return;

  const amount = parseFloat(amountInput.value) || 0;
  const idx = PERIODS.findIndex(p => p.key === currentPeriodKey);
  if (idx === -1) return;

  const indexReturns = medianByPeriod(STATIC_DATA.index);
  const wsbReturns = medianByPeriod(STATIC_DATA.wsb);
  const indexPct = indexReturns[idx];
  const wsbPct = wsbReturns[idx];

  periodLabelEl.textContent = PERIOD_LABELS[currentPeriodKey][currentLang];

  const wsbValue = amount * (1 + (wsbPct ?? 0) / 100);
  const etfValue = amount * (1 + (indexPct ?? 0) / 100);

  wsbEl.textContent = formatCurrency(wsbValue, wsbValue < amount);
  etfEl.textContent = formatCurrency(etfValue, etfValue < amount);

  wsbEl.classList.toggle('negative', wsbValue < amount);
  wsbEl.classList.toggle('positive', wsbValue >= amount);
  etfEl.classList.toggle('negative', etfValue < amount);
  etfEl.classList.toggle('positive', etfValue >= amount);
}

function renderScrollList(containerId, items) {
  const container = document.getElementById(containerId);
  if (!container) return;
  container.innerHTML = '';

  const buildRows = list =>
    list.map(item => {
      const row = document.createElement('div');
      row.className = 'scroll-item';

      const ticker = document.createElement('span');
      ticker.className = 'ticker';
      ticker.textContent = item.ticker;

      const value = document.createElement('span');
      const hasValue = item.value !== null && item.value !== undefined && !Number.isNaN(item.value);
      value.className = `value ${hasValue && item.value < 0 ? 'negative' : 'positive'}`;
      value.textContent = hasValue ? `${item.value >= 0 ? '+' : ''}${item.value.toFixed(2)}%` : '—';

      row.appendChild(ticker);
      row.appendChild(value);
      return row;
    });

  const track = document.createElement('div');
  track.className = 'scroll-track';
  [...buildRows(items), ...buildRows(items)].forEach(row => track.appendChild(row));

  const durationSeconds = Math.max(items.length * 2.2, 8);
  track.style.animationDuration = `${durationSeconds}s`;

  container.appendChild(track);
}


