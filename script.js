function applyLanguage(lang) {
  currentLang = lang;

  document.querySelectorAll('[data-i18n]').forEach(el => {
    const key = el.dataset.i18n;
    if (TRANSLATIONS[key]) el.textContent = TRANSLATIONS[key][lang];
  });

  document.querySelectorAll('.mode-btn').forEach(btn => {
    const span = btn.querySelector('span');
    const labels = PERIOD_LABELS[btn.dataset.period];
    if (span && labels) span.textContent = labels[lang];
  });

  const flagImg = document.getElementById('lang-flag-img');
  if (flagImg) {
    flagImg.src = lang === 'en' ? 'uk.svg.webp' : 'franc.svg.webp';
    flagImg.alt = lang === 'en' ? 'English' : 'Français';
  }

  document.documentElement.lang = lang;
  updateHeroCalculation();
}

